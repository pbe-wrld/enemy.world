/* =========================
   PAGE NAVIGATION
========================= */

const pages = {
    home: document.getElementById("home"),
    profiles: document.getElementById("profiles"),
    about: document.getElementById("about")
};

document.querySelectorAll("[data-page]").forEach(button => {

    button.addEventListener("click", () => {

        const target = button.dataset.page;

        Object.values(pages).forEach(page => {
            page.classList.remove("active");
        });

        if (pages[target]) {
            pages[target].classList.add("active");
        }

        if (target === "profiles") {
            renderProfiles("founder");
        }

    });

});


/* =========================
   PROFILE TABS
========================= */

const profileGrid = document.getElementById("profile-grid");

function renderProfiles(rank) {

    profileGrid.innerHTML = "";

    profiles[rank].forEach(profile => {

        const card = document.createElement("div");

        card.className = "profile-card";

        card.innerHTML = `
            <img
                class="profile-image"
                src="${profile.image}"
                alt="${profile.name}"
            >

            <div class="profile-status"></div>

            <div class="profile-card-info">
                <div class="profile-name">${profile.name}</div>
                <div class="profile-rank">${profile.rank}</div>
            </div>
        `;

        card.addEventListener("click", () => {
            openProfile(profile);
        });

        profileGrid.appendChild(card);

    });
}


document.querySelectorAll(".rank-tab").forEach(tab => {

    tab.addEventListener("click", () => {

        document.querySelectorAll(".rank-tab").forEach(button => {
            button.classList.remove("active");
        });

        tab.classList.add("active");

        renderProfiles(tab.dataset.rank);

    });

});


/* =========================
   PROFILE MODAL
========================= */

const modal = document.getElementById("profile-modal");

const modalImage = document.getElementById("modal-image");
const modalName = document.getElementById("modal-name");
const modalRank = document.getElementById("modal-rank");
const modalDescription = document.getElementById("modal-description");
const modalQuote = document.getElementById("modal-quote");

function openProfile(profile) {

    modalImage.src = profile.image;

    modalName.textContent = profile.name;
    modalRank.textContent = profile.rank;

    modalDescription.textContent = profile.description;
    modalQuote.textContent = `"${profile.quote}"`;

    modal.classList.add("open");

}


document.querySelector(".modal-close").addEventListener("click", () => {
    modal.classList.remove("open");
});


modal.addEventListener("click", event => {

    if (event.target === modal) {
        modal.classList.remove("open");
    }

});


document.addEventListener("keydown", event => {

    if (event.key === "Escape") {
        modal.classList.remove("open");
    }

});


